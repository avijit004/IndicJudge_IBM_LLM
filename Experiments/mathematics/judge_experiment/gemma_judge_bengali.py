import csv
import json
import os
import re
import requests


# ============================================================
# Configuration
# ============================================================

API_URL = "http://172.30.1.83:8080/v1/chat/completions"

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

INPUT_26B = os.path.join(BASE_DIR, "mgsm_bengali_experiment", "gemma4_26b_bengali_responses.csv")

INPUT_31B = os.path.join(BASE_DIR, "mgsm_bengali_experiment", "gemma4_31b_bengali_responses.csv")

OUTPUT_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "gemma_judge_bengali_results.csv")

JUDGE_MODEL = "Gemma-4-31B"

MAX_TOKENS = 4096

# Timeout for one API request
REQUEST_TIMEOUT = 300


# ============================================================
# Judge prompt
# ============================================================

JUDGE_PROMPT = """You are a strict mathematical answer evaluator.

You will be given:

1. A mathematical problem.
2. A candidate solution generated by another model.

Your task is to determine whether the candidate solution is mathematically
and logically correct.

IMPORTANT:
- Independently solve the problem yourself first.
- Then compare the candidate's reasoning and final answer with your own solution.
- Check every important calculation.
- Check whether the reasoning logically follows from the problem.
- Check for arithmetic or mathematical errors.
- Check whether the final answer actually answers the question.
- Do not judge based on writing style, language quality, or how well-written the explanation is.
- A response can be considered correct even if its wording or method differs from your own, provided the mathematics is valid.
- If the candidate reaches the correct final answer using invalid reasoning or an incorrect calculation, mark it incorrect.
- Be strict.

Return ONLY valid JSON in exactly this format:

{{
  "score": 0,
  "correct": false,
  "reason": "Brief explanation of your judgment."
}}

The "score" must be an integer from 0 to 4:

0 = Completely incorrect. The solution is wrong or does not solve the problem.
1 = Mostly incorrect. There is substantial mathematical or logical error.
2 = Partially correct. Some reasoning is correct, but there is a significant error or incomplete solution.
3 = Mostly correct. The approach and reasoning are essentially correct, with only a minor issue.
4 = Fully correct. The reasoning, calculations, and final answer are correct.

The "correct" field must be:
- true only when the solution is mathematically correct overall.
- false otherwise.

Problem:
{question}

Candidate solution:
{response}
"""


# ============================================================
# Read CSV
# ============================================================

def read_csv_file(path):
    """Read a CSV file using UTF-8 with BOM support."""

    if not os.path.exists(path):
        raise FileNotFoundError(f"Input file not found: {path}")

    with open(path, "r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    return rows


# ============================================================
# Load both candidate-response files
# ============================================================

def load_candidate_responses():

    rows_26b = read_csv_file(INPUT_26B)
    rows_31b = read_csv_file(INPUT_31B)

    print("=" * 70)
    print("Bengali Mathematical Response Judging")
    print("=" * 70)

    print(f"Gemma 4 26B responses : {len(rows_26b)}")
    print(f"Gemma 4 31B responses : {len(rows_31b)}")
    print(f"Total responses       : {len(rows_26b) + len(rows_31b)}")
    print(f"Judge model           : {JUDGE_MODEL}")
    print(f"API                   : {API_URL}")
    print(f"Output                : {OUTPUT_FILE}")
    print("=" * 70)

    candidates = []

    for row in rows_26b:
        candidates.append({
            "source_model": "Gemma-4-26B",
            "question_id": row.get("question_id", ""),
            "prompt_id": row.get("prompt_id", ""),
            "question": row.get("question", ""),
            "prompt": row.get("prompt", ""),
            "reasoning_content": row.get("reasoning_content", ""),
            "response": row.get("response", "")
        })

    for row in rows_31b:
        candidates.append({
            "source_model": "Gemma-4-31B",
            "question_id": row.get("question_id", ""),
            "prompt_id": row.get("prompt_id", ""),
            "question": row.get("question", ""),
            "prompt": row.get("prompt", ""),
            "reasoning_content": row.get("reasoning_content", ""),
            "response": row.get("response", "")
        })

    return candidates


# ============================================================
# Parse JSON from judge response
# ============================================================

def parse_json_response(text):

    if not text:
        raise ValueError("Judge returned an empty response.")

    text = text.strip()

    # --------------------------------------------------------
    # First attempt: response itself is JSON
    # --------------------------------------------------------

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    # --------------------------------------------------------
    # Remove markdown code fences
    # --------------------------------------------------------

    cleaned = re.sub(
        r"```(?:json)?\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    cleaned = cleaned.replace("```", "").strip()

    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        pass

    # --------------------------------------------------------
    # Find first JSON object
    # --------------------------------------------------------

    start = cleaned.find("{")
    end = cleaned.rfind("}")

    if start != -1 and end != -1 and end > start:

        candidate = cleaned[start:end + 1]

        try:
            return json.loads(candidate)
        except json.JSONDecodeError:
            pass

    raise ValueError(
        f"Could not parse JSON from judge response:\n{text}"
    )


# ============================================================
# Judge one response
# ============================================================

def judge_response(question, response):

    prompt = JUDGE_PROMPT.replace(
        "{question}",
        question
    ).replace(
        "{response}",
        response
    )

    payload = {
        "model": JUDGE_MODEL,
        "messages": [
            {
                "role": "user",
                "content": prompt
            }
        ],
        "temperature": 0.0,
        "max_tokens": MAX_TOKENS
    }

    response_api = requests.post(
        API_URL,
        json=payload,
        timeout=REQUEST_TIMEOUT
    )

    response_api.raise_for_status()

    data = response_api.json()

    choices = data.get("choices", [])

    if not choices:
        raise ValueError(
            f"No choices returned by server:\n{data}"
        )

    message = choices[0].get("message", {})

    # Gemma may put the answer here
    content = message.get("content", "")

    # Keep reasoning separately if available
    reasoning = message.get("reasoning_content", "")

    # Sometimes content can be None
    if content is None:
        content = ""

    if not content.strip():
        raise ValueError(
            "Judge returned empty final content.\n"
            f"Reasoning content:\n{reasoning}"
        )

    parsed = parse_json_response(content)

    score = parsed.get("score")
    correct = parsed.get("correct")
    reason = parsed.get("reason", "")

    # --------------------------------------------------------
    # Validate score
    # --------------------------------------------------------

    try:
        score = int(score)
    except (TypeError, ValueError):
        raise ValueError(
            f"Invalid score returned: {score}"
        )

    if score not in [0, 1, 2, 3, 4]:
        raise ValueError(
            f"Score must be between 0 and 4, got {score}"
        )

    # --------------------------------------------------------
    # Validate correct
    # --------------------------------------------------------

    if isinstance(correct, str):
        correct_lower = correct.lower().strip()

        if correct_lower == "true":
            correct = True
        elif correct_lower == "false":
            correct = False
        else:
            raise ValueError(
                f"Invalid correct value: {correct}"
            )

    elif not isinstance(correct, bool):
        raise ValueError(
            f"Invalid correct value: {correct}"
        )

    return {
        "score": score,
        "correct": correct,
        "reason": reason,
        "raw_judge_response": content,
        "judge_reasoning": reasoning
    }


# ============================================================
# Checkpoint handling
# ============================================================

FIELDNAMES = [
    "source_model",
    "question_id",
    "prompt_id",
    "question",
    "prompt",
    "reasoning_content",
    "response",
    "judge_model",
    "score",
    "correct",
    "reason",
    "raw_judge_response",
    "judge_reasoning"
]


def load_completed_keys():

    completed = set()

    if not os.path.exists(OUTPUT_FILE):
        return completed

    with open(
        OUTPUT_FILE,
        "r",
        encoding="utf-8-sig",
        newline=""
    ) as f:

        reader = csv.DictReader(f)

        for row in reader:

            key = (
                row.get("source_model", ""),
                row.get("question_id", ""),
                row.get("prompt_id", ""),
                row.get("judge_model", "")
            )

            completed.add(key)

    return completed


# ============================================================
# Save one result
# ============================================================

def save_result(result):

    file_exists = os.path.exists(OUTPUT_FILE)

    os.makedirs(
        os.path.dirname(OUTPUT_FILE),
        exist_ok=True
    )

    with open(
        OUTPUT_FILE,
        "a",
        encoding="utf-8-sig",
        newline=""
    ) as f:

        writer = csv.DictWriter(
            f,
            fieldnames=FIELDNAMES
        )

        if not file_exists:
            writer.writeheader()

        writer.writerow(result)

        f.flush()


# ============================================================
# Main
# ============================================================

def main():

    candidates = load_candidate_responses()

    if len(candidates) != 100:
        print()
        print(
            f"WARNING: Expected 100 responses, "
            f"but found {len(candidates)}."
        )
        print()

    completed = load_completed_keys()

    print(
        f"Already completed judgments: {len(completed)}"
    )

    remaining = [
        c for c in candidates
        if (
            c["source_model"],
            c["question_id"],
            c["prompt_id"],
            JUDGE_MODEL
        ) not in completed
    ]

    print(
        f"Remaining judgments: {len(remaining)}"
    )

    print("=" * 70)

    if not remaining:
        print("All Bengali responses have already been judged.")
        return

    for index, candidate in enumerate(remaining, start=1):

        source_model = candidate["source_model"]
        question_id = candidate["question_id"]
        prompt_id = candidate["prompt_id"]

        print()
        print(
            f"[{index}/{len(remaining)}] "
            f"{source_model} | "
            f"Question {question_id} | "
            f"Prompt {prompt_id}"
        )

        try:

            result = judge_response(
                candidate["question"],
                candidate["response"]
            )

            output_row = {
                "source_model": source_model,
                "question_id": question_id,
                "prompt_id": prompt_id,
                "question": candidate["question"],
                "prompt": candidate["prompt"],
                "reasoning_content": candidate["reasoning_content"],
                "response": candidate["response"],
                "judge_model": JUDGE_MODEL,
                "score": result["score"],
                "correct": result["correct"],
                "reason": result["reason"],
                "raw_judge_response": result["raw_judge_response"],
                "judge_reasoning": result["judge_reasoning"]
            }

            save_result(output_row)

            print(
                f"  Score   : {result['score']}"
            )
            print(
                f"  Correct : {result['correct']}"
            )
            print(
                f"  Reason  : {result['reason']}"
            )

        except Exception as e:

            print(
                f"  ERROR: {e}"
            )

            print(
                "  Skipping this response. "
                "It can be retried by running the script again."
            )

            continue

    print()
    print("=" * 70)
    print("Bengali Gemma judging completed.")
    print(f"Results saved to:")
    print(OUTPUT_FILE)
    print("=" * 70)


if __name__ == "__main__":
    main()
