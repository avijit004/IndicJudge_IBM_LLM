# Judge one response
# ============================================================

def judge_response(question, response, reasoning_content, correct_answer, prompt_id, generation_prompt):

    if not isinstance(generation_prompt, str) or not generation_prompt.strip():
        raise ValueError("Original generation prompt must be a nonempty string.")

    prompt_intent = PROMPT_INTENTS.get(prompt_id, "Unknown prompt type.")

    prompt = JUDGE_PROMPT.format(
        question=question,
        response=response,
        reasoning_content=reasoning_content,
        correct_answer=correct_answer,
        prompt_intent=prompt_intent,
        generation_prompt=generation_prompt,
    )

    payload = {
        "model": JUDGE_MODEL,
        "messages": [
            {
                "role": "user",
                "content": prompt
            }
        ],
        "temperature": 0.0,
        "max_tokens": MAX_TOKENS,
        "chat_template_kwargs": {"enable_thinking": True},
        "reasoning_budget_tokens": REASONING_BUDGET_TOKENS,
        "reasoning_budget_message": REASONING_BUDGET_MESSAGE,
        "response_format": {"type": "json_object", "schema": JUDGMENT_SCHEMA}
    }

    response_api = requests.post(
        API_URL,
        json=payload,
        timeout=REQUEST_TIMEOUT
    )

    response_api.raise_for_status()

    data = response_api.json()

    choices = data.get("choices", [])

    if not choices:
        raise ValueError(
            f"No choices returned by server:\n{data}"
        )

    finish_reason = choices[0].get("finish_reason")
    if finish_reason != "stop":
        raise ValueError(
            f"Judge did not complete normally (finish_reason={finish_reason!r}). "
            "This judgment will not be saved; retry after checking generation settings."
        )

    message = choices[0].get("message", {})

    content = message.get("content", "")
    reasoning = message.get("reasoning_content", "")

    if content is None:
        content = ""

    if not content.strip():
        raise ValueError(
            "Judge returned empty final content.\n"
            f"Reasoning content:\n{reasoning}"
        )

    parsed = parse_json_response(content)
    if not isinstance(parsed, dict):
        raise ValueError("Judge response must be a JSON object.")

    answer_correct = parsed.get("answer_correct")
    reasoning_quality = parsed.get("reasoning_quality")
    follows_prompt_intent = parsed.get("follows_prompt_intent")
    justification = parsed.get("justification", "")

    if type(reasoning_quality) is not int or reasoning_quality not in range(6):
        raise ValueError(f"reasoning_quality must be an integer 0-5, got {reasoning_quality!r}")
    if not isinstance(justification, str) or not justification.strip():
        raise ValueError("justification must be a nonempty string.")

    # Validate booleans
    for field_name, field_val in [("answer_correct", answer_correct), ("follows_prompt_intent", follows_prompt_intent)]:
        if isinstance(field_val, str):
            lower = field_val.lower().strip()
            if lower == "true":
                if field_name == "answer_correct":
                    answer_correct = True
                else:
                    follows_prompt_intent = True
            elif lower == "false":
                if field_name == "answer_correct":
                    answer_correct = False
                else:
                    follows_prompt_intent = False
            else:
                raise ValueError(f"Invalid {field_name} value: {field_val}")
        elif not isinstance(field_val, bool):
            raise ValueError(f"Invalid {field_name} value: {field_val}")

    return {
        "answer_correct": answer_correct,
        "reasoning_quality": reasoning_quality,
        "follows_prompt_intent": follows_prompt_intent,
        "justification": justification,
        "raw_judge_response": content,
        "judge_reasoning": reasoning
    }


