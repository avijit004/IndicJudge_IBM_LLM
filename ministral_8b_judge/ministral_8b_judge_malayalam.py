def select_candidates(candidates, question_ids, source_model):
    """Select five fixed questions, preserving all P1-P5 for each requested model."""
    ids = tuple(str(q).strip() for q in question_ids)
    if len(ids) != 5 or len(set(ids)) != 5 or any(not q for q in ids):
        raise ValueError("Select exactly five distinct, nonempty question IDs.")
    model_names = {"26b": ("Gemma-4-26B",), "31b": ("Gemma-4-31B",),
                   "both": ("Gemma-4-26B", "Gemma-4-31B")}
    if source_model not in model_names:
        raise ValueError("source_model must be both, 26b, or 31b.")
    indexed = {}
    for candidate in candidates:
        key = (candidate["source_model"], candidate["question_id"].strip(), candidate["prompt_id"])
        if key in indexed:
            raise ValueError(f"Duplicate candidate: {key}")
        indexed[key] = candidate
    selected = []
    for model in model_names[source_model]:
        for question_id in ids:
            for prompt_id in PROMPT_INTENTS:
                key = (model, question_id, prompt_id)
                if key not in indexed:
                    raise ValueError(f"Missing selected candidate: {key}")
                selected.append(indexed[key])
    return selected


def main(*, check_data=False, question_ids=DEFAULT_QUESTION_IDS, source_model=DEFAULT_SOURCE_MODEL):

    ground_truth = load_ground_truth()

    candidates = load_candidate_responses()
    candidates = select_candidates(candidates, question_ids, source_model)
    validate_candidates(candidates, ground_truth)
    print(f"Selected question IDs: {', '.join(question_ids)} | Source models: {source_model}")
    print(f"Selected judgments: {len(candidates)} (5 questions x 5 prompts per source model)")
    salvaged = sum(c["response"].startswith("[SALVAGED FROM REASONING]") for c in candidates)
    print(f"Candidate provenance: {len(candidates) - salvaged} unmarked responses; "
          f"{salvaged} responses marked as salvaged from reasoning.")
    if salvaged:
        print("Salvaged responses are included as stored; their markers remain in the output CSV.")

    if check_data:
        print(f"Offline validation passed: {len(ground_truth)} references; {len(candidates)} selected responses.")
        return 0

    completed = load_completed_keys()

    remaining = [
        c for c in candidates
        if (
            c["source_model"],
            c["question_id"],
            c["prompt_id"],
            JUDGE_MODEL
        ) not in completed
    ]

    previously_completed = len(candidates) - len(remaining)
    succeeded = 0
    failed = 0
    print(f"Already completed judgments: {previously_completed}")
    print(f"Remaining judgments: {len(remaining)}")

    print("=" * 70)

    if not remaining:
        print(f"All selected {LANGUAGE.title()} responses have already been judged.")
        print(f"Previously completed: {previously_completed} | Successful: 0 | Failed: 0")
        return 0

    verify_server_context()
    print(f"Ministral reasoning: temperature=0.7, top_p=1, top_k=0, min_p=0, seed=42; "
          f"thinking budget={REASONING_BUDGET_TOKENS}, output limit={MAX_TOKENS}.")

    for index, candidate in enumerate(remaining, start=1):

        source_model = candidate["source_model"]
        question_id = candidate["question_id"]
        prompt_id = candidate["prompt_id"]
        correct_answer = ground_truth[question_id]

        print()
        print(
            f"[{index}/{len(remaining)}] "
            f"{source_model} | "
            f"Question {question_id} | "
            f"Prompt {prompt_id}"
        )

        try:

            result = judge_response(
                candidate["question"],
                candidate["response"],
                candidate["reasoning_content"],
                correct_answer,
                prompt_id,
                generation_prompt=candidate["prompt"],
            )

            output_row = {
                "source_model": source_model,
                "question_id": question_id,
                "prompt_id": prompt_id,
                "question": candidate["question"],
                "prompt": candidate["prompt"],
                "reasoning_content": candidate["reasoning_content"],
                "response": candidate["response"],
                "correct_answer": correct_answer,
                "judge_model": JUDGE_MODEL,
                "answer_correct": result["answer_correct"],
                "reasoning_quality": result["reasoning_quality"],
                "follows_prompt_intent": result["follows_prompt_intent"],
                "justification": result["justification"],
                "raw_judge_response": result["raw_judge_response"],
                "judge_reasoning": result["judge_reasoning"]
            }

            save_result(output_row)
            succeeded += 1

            print(
                f"  Answer Correct       : {result['answer_correct']}"
            )
            print(
                f"  Reasoning Quality    : {result['reasoning_quality']}/5"
            )
            print(
                f"  Follows Prompt Intent: {result['follows_prompt_intent']}"
            )
            print(
                f"  Justification        : {result['justification']}"
            )

        except Exception as e:
            failed += 1

            print(
                f"  ERROR: {e}"
            )

            print(
                "  Skipping this response. "
                "It can be retried by running the script again."
            )

            continue

    print()
    print("=" * 70)
    print(f"Previously completed: {previously_completed} | Successful: {succeeded} | Failed: {failed}")
    status = "incomplete" if failed else "completed"
    print(f"{LANGUAGE.title()} Ministral-3-8B-Reasoning five-question subset judging {status}.")
    print(f"Results saved to:")
    print(OUTPUT_FILE)
    print("=" * 70)
    return 1 if failed else 0


