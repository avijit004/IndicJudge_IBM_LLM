def parse_json_response(text):
    """Accept a complete JSON reply or a single enclosing Markdown JSON fence."""
    if not isinstance(text, str) or not text.strip():
        raise ValueError("Judge returned empty or non-string final content.")
    text = text.strip()
    fenced = re.fullmatch(r"```(?:json)?\s*(.*?)\s*```", text, flags=re.IGNORECASE | re.DOTALL)
    if fenced:
        text = fenced.group(1)
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise ValueError("Judge final content must be complete JSON, without surrounding analysis.") from exc


