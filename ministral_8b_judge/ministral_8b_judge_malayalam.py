def verify_server_context():
    """Fail before inference if llama-server has reverted to a small slot context."""
    if not API_URL:
        raise ValueError("Set MINISTRAL_API_URL to your Ministral server /v1/chat/completions endpoint.")
    if not API_URL.endswith("/v1/chat/completions"):
        raise ValueError("MINISTRAL_API_URL must end with /v1/chat/completions")
    server_url = API_URL.rsplit("/v1/", 1)[0]
    models_reply = requests.get(server_url + "/v1/models", timeout=10)
    models_reply.raise_for_status()
    model_ids = [item.get("id") for item in models_reply.json().get("data", [])]
    if JUDGE_MODEL not in model_ids:
        raise RuntimeError(
            f"Expected server alias {JUDGE_MODEL!r}, got {model_ids!r}. "
            "Load mistralai/Ministral-3-8B-Reasoning-2512 with --alias Ministral-3-8B-Reasoning; check MINISTRAL_API_URL."
        )
    props_url = server_url + "/props"
    reply = requests.get(props_url, timeout=10)
    if not reply.ok:
        raise RuntimeError(f"Server preflight HTTP {reply.status_code}: {reply.text[:2000]}")
    data = reply.json()
    context = data.get("default_generation_settings", {}).get("n_ctx")
    if type(context) is not int or context < MIN_CONTEXT_TOKENS:
        raise RuntimeError(
            f"Ministral-3-8B-Reasoning server has {context!r} context tokens per slot; "
            f"this evaluation requires at least {MIN_CONTEXT_TOKENS}. "
            "Restart llama-server with -c 32768 -np 1, then rerun this script. "
            "No candidate text will be truncated."
        )
    print(f"Server preflight passed: {context} tokens per slot; {data.get('total_slots')} slot(s).")


def judge_response(question, response, reasoning_content, correct_answer, prompt_id, generation_prompt):
    if not isinstance(generation_prompt, str) or not generation_prompt.strip():
        raise ValueError("Original generation prompt must be a nonempty string.")

    prompt_intent = PROMPT_INTENTS.get(prompt_id, "Unknown prompt type.")

    prompt = JUDGE_PROMPT.format(
        question=question,
        response=response,
        reasoning_content=reasoning_content,
        correct_answer=correct_answer,
        prompt_intent=prompt_intent,
        generation_prompt=generation_prompt,
    )

    payload = {
        "model": JUDGE_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {
                "role": "user",
                "content": prompt
            }
        ],
        "temperature": 0.7,
        "top_p": 1.0,
        "top_k": 0,
        "min_p": 0.0,
        "seed": 42,
        "max_tokens": MAX_TOKENS,
        "reasoning_budget_tokens": REASONING_BUDGET_TOKENS,
        "reasoning_budget_message": REASONING_BUDGET_MESSAGE,
        "response_format": {"type": "json_object", "schema": JUDGMENT_SCHEMA}
    }

    response_api = requests.post(
        API_URL,
        json=payload,
        timeout=REQUEST_TIMEOUT
    )

    if not response_api.ok:
        raise requests.HTTPError(
            f"Ministral-3-8B-Reasoning HTTP {response_api.status_code} at {API_URL}: "
            f"{response_api.text[:2000]}", response=response_api,
        )

    data = response_api.json()

    choices = data.get("choices", [])

    if not choices:
        raise ValueError(
            f"No choices returned by server:\n{data}"
        )

    finish_reason = choices[0].get("finish_reason")
    if finish_reason != "stop":
        raise ValueError(
            f"Judge did not complete normally (finish_reason={finish_reason!r}, usage={data.get('usage')!r}). "
            "This judgment will not be saved; retry after checking generation settings."
        )

    message = choices[0].get("message", {})

    content = message.get("content", "")
    reasoning = message.get("reasoning_content", "")

    if content is None:
        content = ""

    if not isinstance(content, str) or not content.strip():
        raise ValueError(
            "Judge returned empty final content.\n"
            f"Reasoning content:\n{reasoning}"
        )

    # Parse final JSON first so literal thinking tags inside a justification survive.
    try:
        parse_json_response(content)
    except ValueError:
        stripped = content.lstrip()
        tags = (("[THINK]", "[/THINK]"), ("<think>", "</think>"))
        explicit = next((pair for pair in tags if stripped.startswith(pair[0])), None)
        if explicit:
            opening, closing = explicit
            if closing not in content:
                raise ValueError("Unclosed thinking block; no final judgment will be saved.")
        elif not stripped.startswith(("{", "[", "```")):
            available = [pair for pair in tags if pair[1] in content]
            explicit = min(available, key=lambda pair: content.index(pair[1])) if available else None
        if explicit:
            opening, closing = explicit
            inline_reasoning, content = content.split(closing, 1)
            reasoning = reasoning or inline_reasoning.strip().removeprefix(opening).strip()
            content = content.strip()

    parsed = parse_json_response(content)
    if not isinstance(parsed, dict):
        raise ValueError("Judge response must be a JSON object.")

    if set(parsed) != set(JUDGMENT_SCHEMA["required"]):
        raise ValueError("Judge response must contain exactly the four required judgment fields.")

    answer_correct = parsed.get("answer_correct")
    reasoning_quality = parsed.get("reasoning_quality")
    follows_prompt_intent = parsed.get("follows_prompt_intent")
    justification = parsed.get("justification", "")

    if type(reasoning_quality) is not int or reasoning_quality not in range(6):
        raise ValueError(f"reasoning_quality must be an integer 0-5, got {reasoning_quality!r}")
    if not isinstance(justification, str) or not justification.strip():
        raise ValueError("justification must be a nonempty string.")

    if len(justification) > MAX_JUSTIFICATION_CHARS:
        raise ValueError(f"justification exceeds {MAX_JUSTIFICATION_CHARS} characters.")

    # Validate booleans
    for field_name, field_val in [("answer_correct", answer_correct), ("follows_prompt_intent", follows_prompt_intent)]:
        if isinstance(field_val, str):
            lower = field_val.lower().strip()
            if lower == "true":
                if field_name == "answer_correct":
                    answer_correct = True
                else:
                    follows_prompt_intent = True
            elif lower == "false":
                if field_name == "answer_correct":
                    answer_correct = False
                else:
                    follows_prompt_intent = False
            else:
                raise ValueError(f"Invalid {field_name} value: {field_val}")
        elif not isinstance(field_val, bool):
            raise ValueError(f"Invalid {field_name} value: {field_val}")

    return {
        "answer_correct": answer_correct,
        "reasoning_quality": reasoning_quality,
        "follows_prompt_intent": follows_prompt_intent,
        "justification": justification,
        "raw_judge_response": content,
        "judge_reasoning": reasoning
    }


