def load_ground_truth():
    """Load and validate numeric references from MGSM or GSM question records."""
    with open(QUESTIONS_FILE, "r", encoding="utf-8") as f:
        questions = json.load(f)

    if not isinstance(questions, list) or not questions:
        raise ValueError("questions.json must contain a nonempty list.")

    number_pattern = r"[+-]?(?:[0-9]+|[0-9]{1,3}(?:,[0-9]{3})+)(?:\.[0-9]+)?"
    answer_map = {}
    for index, q in enumerate(questions, start=1):
        if not isinstance(q, dict):
            raise ValueError(f"Invalid question record {index}.")
        raw_id = q.get("question_id")
        if isinstance(raw_id, bool) or not isinstance(raw_id, (str, int)) or not str(raw_id).strip():
            raise ValueError(f"Missing or invalid question_id in record {index}.")
        question_id = str(raw_id).strip()
        if question_id in answer_map:
            raise ValueError(f"Duplicate question_id: {question_id}")

        answer = q.get("answer_number")
        if answer is None or (isinstance(answer, str) and not answer.strip()):
            solution = q.get("answer", "")
            match = re.search(r"####\s*(" + number_pattern + r")\s*\Z", solution) if isinstance(solution, str) else None
            if not match:
                raise ValueError(f"Missing or malformed reference answer for question {question_id}.")
            answer = match.group(1)
        if isinstance(answer, bool) or not isinstance(answer, (str, int, float)) or not re.fullmatch(number_pattern, str(answer).strip()):
            raise ValueError(f"Invalid reference answer for question {question_id}: {answer!r}")
        answer_map[question_id] = str(answer).strip().replace(",", "")

    return answer_map


def validate_candidates(candidates, ground_truth):
    """Fail before any API calls if a candidate cannot be matched to a reference."""
    seen = set()
    for index, candidate in enumerate(candidates, start=1):
        question_id = candidate["question_id"]
        if not isinstance(question_id, str) or not question_id.strip():
            raise ValueError(f"Missing question_id in candidate {index}.")
        question_id = question_id.strip()
        if question_id not in ground_truth:
            raise ValueError(f"No reference answer for candidate question {question_id}.")
        candidate["question_id"] = question_id
        if candidate["prompt_id"] not in PROMPT_INTENTS:
            raise ValueError(f"Invalid prompt_id in candidate {index}: {candidate['prompt_id']!r}")
        if not isinstance(candidate.get("prompt"), str) or not candidate["prompt"].strip():
            raise ValueError(f"Missing original generation prompt in candidate {index}.")
        key = (candidate["source_model"], question_id, candidate["prompt_id"])
        if key in seen:
            raise ValueError(f"Duplicate candidate: {key}")
        seen.add(key)


