FIELDNAMES = [
    "source_model",
    "question_id",
    "prompt_id",
    "question",
    "prompt",
    "reasoning_content",
    "response",
    "correct_answer",
    "judge_model",
    "answer_correct",
    "reasoning_quality",
    "follows_prompt_intent",
    "justification",
    "raw_judge_response",
    "judge_reasoning"
]


def checkpoint_row_is_complete(row):
    """Accept only complete, internally consistent saved judgments."""
    if None in row or any(row.get(name) is None for name in FIELDNAMES):
        return False
    required = ("source_model", "question_id", "prompt_id", "question", "prompt",
                "response", "correct_answer", "judge_model", "justification", "raw_judge_response")
    if any(not row[name].strip() for name in required):
        return False
    if row["source_model"] not in ("Gemma-4-26B", "Gemma-4-31B") or row["prompt_id"] not in PROMPT_INTENTS:
        return False
    if row["reasoning_quality"] not in {str(n) for n in range(6)}:
        return False
    if any(row[name].strip().lower() not in ("true", "false")
           for name in ("answer_correct", "follows_prompt_intent")):
        return False
    try:
        raw = parse_json_response(row["raw_judge_response"])
        if not isinstance(raw, dict) or type(raw.get("reasoning_quality")) is not int:
            return False
        if raw["reasoning_quality"] != int(row["reasoning_quality"]):
            return False
        if raw.get("justification") != row["justification"]:
            return False
        for name in ("answer_correct", "follows_prompt_intent"):
            value = raw.get(name)
            if not isinstance(value, (bool, str)) or str(value).strip().lower() != row[name].strip().lower():
                return False
    except (ValueError, TypeError, KeyError):
        return False
    return True


def load_completed_keys():
    """Recover interrupted output, preserving an original backup before repair."""
    if not os.path.exists(OUTPUT_FILE):
        return set()
    valid_rows = []
    invalid_count = 0
    malformed = False
    with open(OUTPUT_FILE, "r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f, strict=True)
        if reader.fieldnames is None:
            return set()
        if reader.fieldnames != FIELDNAMES:
            raise ValueError(f"Unexpected checkpoint CSV header in {OUTPUT_FILE}; file left unchanged.")
        try:
            for row in reader:
                if checkpoint_row_is_complete(row):
                    valid_rows.append(row)
                else:
                    invalid_count += 1
        except csv.Error:
            # An interrupted quoted multiline field may swallow the remainder.
            # Keep only fully parsed records; preserve all original bytes below.
            malformed = True

    if invalid_count or malformed:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S_%fZ")
        backup = f"{OUTPUT_FILE}.incomplete-{stamp}.bak"
        shutil.copy2(OUTPUT_FILE, backup)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8-sig", newline="",
                                             dir=os.path.dirname(os.path.abspath(OUTPUT_FILE)),
                                             prefix=".ministral-8b-checkpoint-", delete=False) as f:
                temporary = f.name
                writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
                writer.writeheader()
                writer.writerows(valid_rows)
                f.flush()
                os.fsync(f.fileno())
            os.replace(temporary, OUTPUT_FILE)
        finally:
            if temporary and os.path.exists(temporary):
                os.remove(temporary)
        print(f"Recovered checkpoint: retained {len(valid_rows)} complete rows; "
              f"removed {invalid_count} incomplete rows; malformed tail={malformed}.")
        print(f"Original checkpoint preserved at: {backup}")
        print("Unfinished judgments will be retried.")

    return {(r["source_model"], r["question_id"], r["prompt_id"], r["judge_model"])
            for r in valid_rows}


